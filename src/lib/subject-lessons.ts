import type { Exercise, Topic } from "./curriculum";
import type { Subject } from "./subjects";

function question(
  en: string,
  mt: string,
  answer: string,
  aliases: string[],
  choices: string[],
  explanationEn: string,
  explanationMt: string,
): Exercise {
  return {
    prompt: { en, mt },
    answer,
    acceptedAnswers: aliases,
    choices: { en: choices, mt: choices },
    hint: {
      en: explanationEn.split(".")[0] + ".",
      mt: explanationMt.split(".")[0] + ".",
    },
    worked: { en: explanationEn, mt: explanationMt },
  };
}
function lesson(
  year: number,
  subject: Subject,
  id: string,
  en: string,
  mt: string,
  exercises: Exercise[],
): Topic {
  const scienceWords: Record<string, string> = {
    roots: "għeruq",
    petals: "petali",
    fruit: "frott",
    leaves: "weraq",
    seeds: "żrieragħ",
    seed: "żerriegħa",
    petal: "petala",
    flowerpot: "qasrija",
    solid: "solidu",
    liquid: "likwidu",
    gas: "gass",
    freezing: "iffriżar",
    melting: "tidwib",
    evaporating: "evaporazzjoni",
    iron: "ħadid",
    wood: "injam",
    glass: "ħġieġ",
    circuit: "ċirkwit",
    habitat: "ħabitat",
    skeleton: "skeletru",
    copper: "ram",
    plastic: "plastik",
    rubber: "gomma",
    "go out": "tintefa",
    "get brighter": "iddawwal aktar",
    grow: "tikber",
  };
  if (subject === "science")
    exercises = exercises.map((exercise) => ({
      ...exercise,
      choices: {
        en: exercise.choices!.en,
        mt: exercise.choices!.en.map(
          (choice) => scienceWords[choice] || choice,
        ),
      },
    }));
  return {
    id: `Y${year}-${subject.toUpperCase()}-${id}`,
    year,
    subject,
    title: { en, mt },
    icon: subject === "english" ? "Aa" : subject === "maltese" ? "Ħ" : "⚗",
    description:
      "Guided practice with examples, checked short answers and a worked explanation.",
    exercises,
  };
}
